"""
config.py
---------
Центральная конфигурация приложения.
Здесь собраны все "магические числа", идентификаторы моделей и пути,
чтобы не разбрасывать их по всему коду.
"""

import os
import torch

# ---------------------------------------------------------------------------
# Устройство вычислений (GPU, если доступен, иначе CPU)
# ---------------------------------------------------------------------------
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

# ---------------------------------------------------------------------------
# Модели (используются реализации из HuggingFace Transformers)
#
# GroundingDINO: детекция объектов по произвольному текстовому запросу.
# SAM (Segment Anything): сегментация объектов внутри bounding box.
#
# Более крупные модели точнее, но требуют больше видеопамяти и времени.
# Можно переопределить через переменные окружения при необходимости.
# ---------------------------------------------------------------------------
GROUNDING_DINO_MODEL_ID = os.environ.get(
    "GROUNDING_DINO_MODEL_ID", "IDEA-Research/grounding-dino-tiny"
)
SAM_MODEL_ID = os.environ.get("SAM_MODEL_ID", "facebook/sam-vit-base")

# ---------------------------------------------------------------------------
# Пороги по умолчанию для GroundingDINO
#   BOX_THRESHOLD  - минимальная уверенность в наличии объекта (bbox)
#   TEXT_THRESHOLD - минимальная уверенность в соответствии текстовому токену
# ---------------------------------------------------------------------------
DEFAULT_BOX_THRESHOLD = 0.35
DEFAULT_TEXT_THRESHOLD = 0.25

# Максимальное число объектов, обрабатываемых на одном изображении.
# Защита от деградации производительности при "шумных" запросах, которые
# могут дать сотни ложных срабатываний на сложных сценах.
MAX_DETECTIONS_PER_IMAGE = 100

# ---------------------------------------------------------------------------
# Видео
# ---------------------------------------------------------------------------
DEFAULT_FRAME_INTERVAL_SEC = 2.0
MAX_VIDEO_FRAMES = 500  # защита от случайного извлечения тысяч кадров

# ---------------------------------------------------------------------------
# Пути вывода
# ---------------------------------------------------------------------------
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_DIR = os.path.join(BASE_DIR, "outputs")
TMP_DIR = os.path.join(BASE_DIR, "tmp")

os.makedirs(OUTPUT_DIR, exist_ok=True)
os.makedirs(TMP_DIR, exist_ok=True)

# Поддерживаемые форматы экспорта аннотаций
SUPPORTED_EXPORT_FORMATS = ["COCO", "YOLO", "Pascal VOC"]

# Поддерживаемые расширения входных файлов
IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".bmp", ".webp")
VIDEO_EXTENSIONS = (".mp4", ".avi", ".mov", ".mkv", ".webm")

# Логирование
LOG_LEVEL = os.environ.get("LOG_LEVEL", "INFO")
LOG_FILE = os.path.join(BASE_DIR, "app.log")
